function setCookie(name, value) {
    document.cookie = `${name}=${value};path=/;max-age=31536000`;
}
function getCookie(name) {
    const match = document.cookie.match(new RegExp('(^| )' + name + '=([^;]+)'));
    return match ? match[2] : null;
}

let shuffle = getCookie('shuffle') === 'true';
const lastTrack = parseInt(getCookie('lastTrack')) || 0;
const lastPosition = parseFloat(getCookie('lastPosition')) || 0;
let autoplay = getCookie('autoplay') === 'true';
const savedVolume = parseInt(getCookie('bgmVolume')) || 70;

const titleEl = document.getElementById('trackTitle');
const indexEl = document.getElementById('trackIndex');
const barsEl = document.getElementById('bars');
const tracklist = document.getElementById('tracklist');
const btnPlay = document.getElementById('btnPlay');
const btnPrev = document.getElementById('btnPrev');
const btnNext = document.getElementById('btnNext');
const volSlider = document.getElementById('volSlider');
const volVal = document.getElementById('volVal');
const seekSlider = document.getElementById('seekSlider');
const seekVal = document.getElementById('seekVal');

const btnShuffle = document.getElementById('btnShuffle');
btnShuffle.classList.toggle('active', shuffle);

const ctx = new AudioContext();
const gainNode = ctx.createGain();
volSlider.value = savedVolume;
volVal.textContent = savedVolume + '%';
gainNode.gain.value = savedVolume / 100;
gainNode.connect(ctx.destination);

const buffers = new Array(trackList.length).fill(null);
let current = -1;
let playing = false;
let sourceNode = null;
let startTime = 0;   // ctx.currentTime when playback started
let startOffset = 0;  // how far into the track we started from

// decode all tracks upfront
trackList.forEach((t, i) => {
    fetch(t.url)
        .then(r => r.arrayBuffer())
        .then(ab => ctx.decodeAudioData(ab))
        .then(buf => {
            buffers[i] = buf;
            if (i === 0) {
                indexEl.textContent = 'Ready';
                // attempt autoplay once first track is decoded
                if (autoplay && current === lastTrack && !playing) {
                    ctx.resume().then(() => startPlayback(lastPosition));
                }
            }
        })
        .catch(e => console.error('Failed to load track', i, e));
});

// build track buttons
trackList.forEach((t, i) => {
    const btn = document.createElement('button');
    btn.className = 'track-btn';
    btn.innerHTML = `
    <span class="num">${String(i + 1).padStart(2, '0')}</span>
    ${t.cover ? `<img src="${t.cover}" class="track-cover" alt="">` : ''}
    ${t.title}
`;
    btn.addEventListener('click', () => loadTrack(i, true));
    tracklist.appendChild(btn);
});

function getButtons() {
    return tracklist.querySelectorAll('.track-btn');
}

function formatTime(secs) {
    const m = Math.floor(secs / 60);
    const s = Math.floor(secs % 60);
    return `${m}:${s.toString().padStart(2, '0')}`;
}

function getCurrentTime() {
    if (!playing) return startOffset;
    return startOffset + (ctx.currentTime - startTime);
}

const artistEl = document.getElementById('trackArtists');

function loadTrack(index, shouldPlay = false) {
    stopCurrent();

    current = index;
    setCookie('lastTrack', index);
    startOffset = 0;

    const t = trackList[index];

    // title with marquee if too long
    titleEl.textContent = t.title;
    titleEl.classList.remove('scrolling');
    // check after render if it overflows
    requestAnimationFrame(() => {
        if (titleEl.scrollWidth > titleEl.parentElement.clientWidth) {
            titleEl.classList.add('scrolling');
        }
    });

    // artists with links
    artistEl.innerHTML = t.artists.map((a, i) => {
        const link = a.url
            ? `<a href="${a.url}" target="_blank" rel="noopener">${a.name}</a>`
            : `<span>${a.name}</span>`;
        return i < t.artists.length - 1
            ? link + '<span class="separator">&amp;</span>'
            : link;
    }).join('');


    // release link — append to artists if present
    if (t.releaseUrl) {
        titleEl.innerHTML = `<a href="${t.releaseUrl}" target="_blank" rel="noopener">${t.title}</a>`;
    } else {
        titleEl.textContent = t.title;
    }

    indexEl.textContent = `Track ${index + 1} of ${trackList.length}`;
    getButtons().forEach((b, i) => b.classList.toggle('active', i === index));

    seekSlider.value = 0;
    seekVal.textContent = '0:00';

    if (shouldPlay) startPlayback(0);
    else setPlaying(false);

    const albumEl = document.getElementById('trackAlbum');

    if (t.album) {
        albumEl.innerHTML = t.releaseUrl
            ? `<a href="${t.releaseUrl}" target="_blank" rel="noopener">${t.album}</a>`
            : t.album;
    } else {
        albumEl.textContent = '';
    }

    const coverEl = document.getElementById('coverArt');

// inside loadTrack:
    if (t.cover) {
        coverEl.src = t.cover;
        coverEl.classList.add('visible');
    } else {
        coverEl.src = '';
        coverEl.classList.remove('visible');
    }
}

function startPlayback(offset) {
    if (current === -1) return;
    const buf = buffers[current];
    if (!buf) {
        indexEl.textContent = 'Still loading...';
        return;
    }

    if (ctx.state === 'suspended') ctx.resume();

    sourceNode = ctx.createBufferSource();
    sourceNode.buffer = buf;
    sourceNode.connect(gainNode);
    sourceNode.start(0, offset);
    sourceNode.onended = () => {
        if (playing) {
            let next;
            if (shuffle) {
                do { next = Math.floor(Math.random() * trackList.length); }
                while (next === current && trackList.length > 1);
            } else {
                next = (current + 1) % trackList.length;
            }
            loadTrack(next, true);
        }
    };

    startTime = ctx.currentTime;
    startOffset = offset;
    setPlaying(true);
}

function stopCurrent() {
    if (sourceNode) {
        sourceNode.onended = null;
        sourceNode.stop();
        sourceNode.disconnect();
        sourceNode = null;
    }
    startOffset = getCurrentTime();
    setPlaying(false);
}

function setPlaying(state) {
    playing = state;
    btnPlay.innerHTML = state ? '&#9646;&#9646;' : '&#9654;';
    barsEl.classList.toggle('playing', state);
}

// seek bar update loop
setInterval(() => {
    if (!playing || current === -1) return;
    const buf = buffers[current];
    if (!buf) return;
    const ct = getCurrentTime();
    seekSlider.value = (ct / buf.duration) * 100;
    seekVal.textContent = formatTime(ct);
    setCookie('lastPosition', ct);   // add this line
}, 200);

// controls
btnPlay.addEventListener('click', () => {
    if (ctx.state === 'suspended') ctx.resume();
    if (current === -1) {
        loadTrack(0, true);
        return;
    }
    if (playing) {
        stopCurrent();
    } else {
        startPlayback(startOffset);
    }
});

btnPrev.addEventListener('click', () => {
    const prev = current <= 0 ? trackList.length - 1 : current - 1;
    loadTrack(prev, playing);
});

btnNext.addEventListener('click', () => {
    let next;
    if (shuffle) {
        do { next = Math.floor(Math.random() * trackList.length); }
        while (next === current && trackList.length > 1);
    } else {
        next = current >= trackList.length - 1 ? 0 : current + 1;
    }
    loadTrack(next, playing);
});

btnShuffle.addEventListener('click', () => {
    shuffle = !shuffle;
    setCookie('shuffle', shuffle);
    btnShuffle.classList.toggle('active', shuffle);
});

const chkAutoplay = document.getElementById('chkAutoplay');
chkAutoplay.checked = autoplay;
chkAutoplay.addEventListener('change', () => {
    autoplay = chkAutoplay.checked;
    setCookie('autoplay', autoplay);
});

seekSlider.addEventListener('input', () => {
    const buf = buffers[current];
    if (!buf) return;
    const offset = (seekSlider.value / 100) * buf.duration;
    seekVal.textContent = formatTime(offset);
    if (playing) {
        stopCurrent();
        startPlayback(offset);
    } else {
        startOffset = offset;
    }
});

volSlider.addEventListener('input', () => {
    const v = volSlider.value / 100;
    gainNode.gain.value = v;
    volVal.textContent = volSlider.value + '%';
    setCookie('bgmVolume', volSlider.value); // add this
});

// restore last track and position
loadTrack(lastTrack, false);
if (lastPosition > 0) {
    startOffset = lastPosition;
    seekVal.textContent = formatTime(lastPosition);
}